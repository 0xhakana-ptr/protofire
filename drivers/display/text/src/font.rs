//! drivers/display/text/src/font.rs
//!
//! The 8x16 bitmap font the console draws with.
//!
//! ## Provenance
//!
//! This font was made for this project, and its source of truth is a table of
//! ASCII art rather than a binary blob: `tools/generate_font.py` holds one
//! 16-row picture per glyph and prints the bytes below.  A reader can therefore
//! check any glyph against a picture of it, which is what "original work" means
//! here rather than a licence claim nobody can verify.
//!
//! Licence: Apache-2.0, the same as the kernel.
//!
//! ## The shape
//!
//! 96 glyphs of 16 bytes, one byte per row, MSB leftmost.  The first 95 are
//! ASCII `0x20` to `0x7E`; the last is the fallback drawn for any byte outside
//! that range, which is what keeps the console from dropping a character it
//! cannot draw, a dropped byte in a log is worse than a visible box.
//!
//! The slice is `include!`d rather than written here so the numbers stay in one
//! place: re-running the generator replaces the table and nothing else.

