/// How many glyphs the table holds: the printable range and the fallback.
pub const GLYPH_COUNT: usize = 96;

/// The rows of `byte`, or the fallback's when it has no glyph.
///
/// The answer is a reference rather than a copy because a glyph is sixteen
/// bytes and a console draws hundreds per screen.  A caller that mutates it
/// would be mutating the font, which is why it is a shared reference.
pub fn glyph(byte: u8) -> &'static [u8; GLYPH_HEIGHT] {
    let index = if (FIRST_GLYPH..=LAST_GLYPH).contains(&byte) {
        (byte - FIRST_GLYPH) as usize
    } else {
        // The fallback is the last entry, so a byte outside the range is drawn
        // as the box rather than dropped.
        GLYPH_COUNT - 1
    };
    let start = index * GLYPH_HEIGHT;
    // The cast is exact: the slice has `GLYPH_HEIGHT` bytes by construction,
    // and a `try_into` here would be a runtime check on a compile-time fact.
    GLYPHS[start..start + GLYPH_HEIGHT]
        .try_into()
        .expect("a glyph is GLYPH_HEIGHT bytes")
}

/// Whether the pixel at `column` of one glyph row is set.
///
/// The bit order is the table's: the leftmost pixel is the most significant
/// bit, which is what the generator's ASCII art reads as.  A console that read
/// it the other way would draw every glyph mirrored, and a mirrored glyph is
/// legible enough to pass a glance and wrong enough to fail a screenshot.
pub const fn row_pixel(row: u8, column: usize) -> bool {
    row & (0x80 >> column) != 0
}

