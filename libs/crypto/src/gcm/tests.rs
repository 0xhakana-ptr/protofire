// AES-128-GCM test vectors

#[test]
fn aes128_gcm_encrypt_decrypt_round_trip() {
    let key: [u8; 16] = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f,
    ];
    let nonce: [u8; 12] = [
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b,
    ];
    let aad = b"authenticated";
    let plaintext = b"Hello, AES-128-GCM!";

    let (ciphertext, tag) = crate::gcm::aes128_gcm_encrypt(&key, &nonce, aad, plaintext);
    assert_eq!(ciphertext.len(), plaintext.len());

    let decrypted = crate::gcm::aes128_gcm_decrypt(&key, &nonce, aad, &ciphertext, &tag)
        .expect("decryption should succeed");
    assert_eq!(decrypted, plaintext);
}

#[test]
fn aes128_gcm_tag_verification_fails_with_wrong_key() {
    let key1: [u8; 16] = [0x00; 16];
    let key2: [u8; 16] = [0x01; 16];
    let nonce: [u8; 12] = [0x00; 12];
    let plaintext = b"sensitive";

    let (ciphertext, tag) = crate::gcm::aes128_gcm_encrypt(&key1, &nonce, b"", plaintext);
    let result = crate::gcm::aes128_gcm_decrypt(&key2, &nonce, b"", &ciphertext, &tag);
    assert!(result.is_err());
}

#[test]
fn aes128_gcm_empty_plaintext() {
    let key: [u8; 16] = [0x42; 16];
    let nonce: [u8; 12] = [0x00; 12];
    let (ciphertext, tag) = crate::gcm::aes128_gcm_encrypt(&key, &nonce, b"", b"");
    assert_eq!(ciphertext.len(), 0);
    assert_eq!(tag.len(), 16);
    // Should be able to decrypt empty ciphertext.
    let decrypted = crate::gcm::aes128_gcm_decrypt(&key, &nonce, b"", &ciphertext, &tag)
        .expect("empty decryption");
    assert!(decrypted.is_empty());
}

#[test]
fn aes128_gcm_known_vector() {
    // NIST GCM spec test case 3 (AES-128).
    let key: [u8; 16] = [
        0xfe, 0xff, 0xe9, 0x92, 0x86, 0x65, 0x73, 0x1c, 0x6d, 0x6a, 0x8f, 0x94, 0x67, 0x30, 0x83,
        0x08,
    ];
    let nonce: [u8; 12] = [
        0xca, 0xfe, 0xba, 0xbe, 0xfa, 0xce, 0xdb, 0xad, 0xde, 0xca, 0xf8, 0x88,
    ];
    let aad = [
        0xfe, 0xed, 0xfa, 0xce, 0xde, 0xad, 0xbe, 0xef, 0xfe, 0xed, 0xfa, 0xce, 0xde, 0xad, 0xbe,
        0xef, 0xab, 0xad, 0xda, 0xd2,
    ];
    let plaintext = [
        0xd9, 0x31, 0x32, 0x25, 0xf8, 0x84, 0x06, 0xe5, 0xa5, 0x59, 0x09, 0xc5, 0xaf, 0xf5, 0x26,
        0x9a, 0x86, 0xa7, 0xa9, 0x53, 0x15, 0x34, 0xf7, 0xda, 0x2e, 0x4c, 0x30, 0x3d, 0x8a, 0x31,
        0x8a, 0x72, 0x1c, 0x3c, 0x0c, 0x95, 0x95, 0x68, 0x09, 0x53, 0x2f, 0xcf, 0x0e, 0x24, 0x49,
        0xa6, 0xb5, 0x25, 0xb1, 0x6a, 0xed, 0xf5, 0xaa, 0x0d, 0xe6, 0x57, 0xba, 0x63, 0x7b, 0x39,
        0x1a, 0xaf, 0xd2, 0x55,
    ];
    let expected_ct = [
        0x42, 0x83, 0x1e, 0xc2, 0x21, 0x77, 0x74, 0x24, 0x4b, 0x72, 0x21, 0xb7, 0x84, 0xd0, 0xd4,
        0x9c, 0xe3, 0xaa, 0x21, 0x2f, 0x2c, 0x02, 0xa4, 0xe0, 0x35, 0xc1, 0x7e, 0x23, 0x29, 0xac,
        0xa1, 0x2e, 0x21, 0xd5, 0x14, 0xb2, 0x54, 0x66, 0x93, 0x1c, 0x7d, 0x8f, 0x6a, 0x5a, 0xac,
        0x84, 0xaa, 0x05, 0x1b, 0xa3, 0x0b, 0x39, 0x6a, 0x0a, 0xac, 0x97, 0x3d, 0x58, 0xe0, 0x91,
        0x47, 0x3f, 0x59, 0x85,
    ];
    let expected_tag = [
        0xda, 0x80, 0xce, 0x83, 0x0c, 0xfd, 0xa0, 0x2d, 0xa2, 0xa2, 0x18, 0xa1, 0x74, 0x4f, 0x4c,
        0x76,
    ];
    let (ciphertext, tag) = crate::gcm::aes128_gcm_encrypt(&key, &nonce, &aad, &plaintext);
    assert_eq!(ciphertext, expected_ct);
    assert_eq!(tag, expected_tag);

    // Decryption must round-trip and reject a corrupted tag.
    let decrypted =
        crate::gcm::aes128_gcm_decrypt(&key, &nonce, &aad, &ciphertext, &tag).expect("GCM decrypt");
    assert_eq!(decrypted, plaintext);
    let mut bad_tag = tag;
    bad_tag[0] ^= 0x01;
    assert!(crate::gcm::aes128_gcm_decrypt(&key, &nonce, &aad, &ciphertext, &bad_tag).is_err());
}
