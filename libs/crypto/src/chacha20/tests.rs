#[test]
fn chacha20_keystream_is_reproducible() {
    let key = sha256(b"test-key-seed");
    let nonce = sha256(b"test-nonce-seed");
    let nonce_12: [u8; 12] = [
        nonce[0], nonce[1], nonce[2], nonce[3], nonce[4], nonce[5], nonce[6], nonce[7], nonce[8],
        nonce[9], nonce[10], nonce[11],
    ];

    let mut out1 = [0u8; 128];
    let mut out2 = [0u8; 128];
    crate::chacha20::chacha20_keystream(&key, &nonce_12, 0, &mut out1);
    crate::chacha20::chacha20_keystream(&key, &nonce_12, 0, &mut out2);
    assert_eq!(out1, out2);
}
