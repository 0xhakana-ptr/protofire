#!/usr/bin/env sh
# File: scripts/check-commits.sh
# Purpose: Run the commit-message hook over a range of commits.
#
# ## Why this exists
#
# `scripts/hooks/commit-msg` is installed by hand and runs on `git commit`.  A
# contributor who never installs it writes whatever they like, and until this
# script existed nothing in the gate read `git log`: a commit message could
# break every rule in `docs/fmts/commits.md` and `sh scripts/verify.sh p3`
# stayed green.  A rule that only a hook nobody installed enforces is a rule
# with no gate behind it.
#
# ## It does not reimplement the rules
#
# The range is walked, each commit's message is written to a file, and the file
# is handed to the same hook.  There is one implementation of the rules, in
# `scripts/hooks/commit-msg`, so the check a contributor gets at `git commit`
# and the check the gate runs cannot disagree.  A second implementation would
# be a second thing to keep in step, which is the drift this tree's gates exist
# to refuse.
#
# ## The range
#
# `origin/master..HEAD` when that ref resolves: the commits this branch adds.  A
# commit already on `origin/master` is published history, and
# `docs/fmts/commits.md` says the rules are not retroactive.
#
# On `master` with nothing unpushed the range is empty, which is the normal
# case for a maintainer who commits and pushes in the same session.  That is
# not a hole: the hook is installed in that maintainer's clone, so the message
# was checked at `git commit`, and this script's job is the pull request whose
# author may not have installed it.
#
# When `origin/master` does not resolve, which is a clone that has never
# fetched and a CI checkout that fetched one commit, the fork point cannot be
# found.  The script then checks `HEAD` alone and **says so**: checking one
# commit is less than checking the range, and a reader has to be able to tell
# which happened.  It does not fall back to an empty range, because a gate that
# silently checked nothing is the exact failure this script exists to catch.
#
# Usage:
#   sh scripts/check-commits.sh                  # origin/master..HEAD, or HEAD
#   sh scripts/check-commits.sh <base>..<head>   # an explicit range

set -eu

cd "$(dirname "$0")/.."

GIT="${GIT:-git}"

if [ "$#" -ge 1 ]; then
    RANGE="$1"
    NOTE=""
elif "$GIT" rev-parse --verify --quiet origin/master >/dev/null 2>&1; then
    RANGE="origin/master..HEAD"
    NOTE=""
else
    RANGE="HEAD"
    NOTE="origin/master did not resolve, so only HEAD was checked; fetch to check a range"
fi

hook="scripts/hooks/commit-msg"
[ -x "$hook" ] || {
    printf 'check-commits: %s is not executable\n' "$hook" >&2
    exit 1
}

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT INT TERM

# Resolve the range before walking it, so a range that names a commit this
# clone does not have is a failure with a message rather than an empty list
# that reads as a pass.
if ! commits="$("$GIT" rev-list "$RANGE" 2>"$work/err")"; then
    printf 'check-commits: cannot resolve the range `%s`:\n' "$RANGE" >&2
    sed 's/^/  /' "$work/err" >&2
    printf '\nAn unresolvable range is a failure, not a pass: a gate that\n' >&2
    printf 'checked no commit would report the result this script exists to\n' >&2
    printf 'refuse.\n' >&2
    exit 1
fi

count=0
failed=0
for commit in $commits; do
    "$GIT" log -1 --format=%B "$commit" >"$work/message"

    # A merge commit is generated by git and the hook exempts it by subject.
    # Passing it through anyway is what keeps this script from having an
    # opinion the hook does not have.
    if "$hook" "$work/message" >"$work/out" 2>&1; then
        count=$((count + 1))
        continue
    fi

    subject="$("$GIT" log -1 --format=%s "$commit")"
    short="$("$GIT" rev-parse --short "$commit")"
    printf 'check-commits: %s %s\n' "$short" "$subject" >&2
    sed 's/^/  /' "$work/out" >&2
    failed=$((failed + 1))
done

if [ "$failed" -ne 0 ]; then
    printf '\ncheck-commits: %d of %d commit(s) in `%s` break the message rules.\n' \
        "$failed" "$((count + failed))" "$RANGE" >&2
    printf 'docs/fmts/commits.md is the specification.  Fix the message with\n' >&2
    printf 'git commit --amend or a rebase, then re-run this check.\n' >&2
    exit 1
fi

printf 'check-commits: %d commit(s) in `%s`, every message obeys the hook\n' \
    "$count" "$RANGE"
[ -z "$NOTE" ] || printf 'check-commits: %s\n' "$NOTE"
